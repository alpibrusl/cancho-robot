#!/usr/bin/env python3
"""Generate src/robot.cho, this robot's calibration and buses, from LeRobot's calibration files.

The numbers come from the files LeRobot wrote (`lerobot-calibrate`), not from a person: per arm and joint, the
servo id, the homing offset, the range and the drive mode. The same three numbers are stored IN each servo
(Homing_Offset at 31, Min/Max_Position_Limit at 9 and 11), which is how the controller recognises an arm on a
bus: by what its servos say, never by which USB adapter it is plugged into (on 2026-10-12 the arm chains were on
the opposite adapters from lex-robot's record; docs/research-log.md).

    python3 scripts/gen_robot.py tests/fixtures/calibration > src/robot.cho
    python3 scripts/gen_robot.py tests/fixtures/calibration --check src/robot.cho   # CI
"""
import hashlib
import json
import sys
from pathlib import Path

JOINTS = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll", "gripper"]
SIDES = ["left", "right"]
# Which file calibrates which PHYSICAL arm. Measured on 2026-10-12 by moving the left arm by hand while reading both
# buses: the physical left arm's servos carry `xle_right.json`'s numbers (LeRobot calibrated it under that name), and
# the right arm's carry `xle_left.json`'s. The controller names arms by where they are on the robot, because that is
# what the safety core's mounts mean; the file names are LeRobot's and stay as they are.
FILE_OF = {"left": "xle_right.json", "right": "xle_left.json"}
# The buses the controller may open: the two USB adapters on the Pi, and the simulated bus (sim/fake_bus.py).
# Which arm is on which is read from the servos, so the table is a set of devices, not a map to arms.
DEVICES = [
    "/dev/serial/by-id/usb-1a86_USB_Single_Serial_5B61033220-if00",
    "/dev/serial/by-id/usb-1a86_USB_Single_Serial_5B3D043715-if00",
]
SIM_DEVICES = ["/tmp/cancho-robot-sim/left", "/tmp/cancho-robot-sim/right"]


def table(name, cal, field):
    lines = [f"pub fn {name}(side: int, joint: int) -> [] int {{"]
    for s, side in enumerate(SIDES):
        for j, joint in enumerate(JOINTS):
            lines.append(f"    if side == {s} && joint == {j} {{\n        return {cal[side][joint][field]};\n    }}")
    lines.append("    return -1;\n}")
    return "\n".join(lines)


def devices(name, paths):
    lines = [f"pub fn {name}(k: int) -> [] &static [byte] {{"]
    for k, p in enumerate(paths):
        lines.append(f"    if k == {k} {{\n        return \"{p}\\0\";\n    }}")
    lines.append("    return \"\";\n}")
    return "\n".join(lines)


def generate(folder):
    folder = Path(folder)
    cal, digests = {}, []
    for side in SIDES:
        path = folder / FILE_OF[side]
        raw = path.read_bytes()
        digests.append(f"// {side}: {path.name}: sha256 {hashlib.sha256(raw).hexdigest()}")
        data = json.loads(raw)
        if list(data) != JOINTS:
            raise SystemExit(f"{path}: joints {list(data)}, expected {JOINTS}")
        cal[side] = data
    head = f"""edition 5;

module robot;

// GENERATED by scripts/gen_robot.py from LeRobot's calibration files -- do not edit; regenerate, and CI checks it.
{chr(10).join(digests)}
// Side 0 (left) is calibrated by {FILE_OF["left"]}, side 1 (right) by {FILE_OF["right"]}: the PHYSICAL arms, measured
// by hand on 2026-10-12 (LeRobot's file names are the other way round; scripts/gen_robot.py says how it was found).
//
// Sides: 0 left, 1 right. Joints: 0 shoulder_pan, 1 shoulder_lift, 2 elbow_flex, 3 wrist_flex, 4 wrist_roll,
// 5 gripper. Each servo stores its own homing offset and range (registers 31, 9 and 11); `core.identify` reads them
// and answers which side a bus carries, so a cable moved between adapters is recognised, not believed.

pub fn left() -> [] int {{
    return 0;
}}

pub fn right() -> [] int {{
    return 1;
}}

pub fn joints() -> [] int {{
    return {len(JOINTS)};
}}

pub fn gripper() -> [] int {{
    return {JOINTS.index("gripper")};
}}

pub fn devices() -> [] int {{
    return {len(DEVICES)};
}}
"""
    body = [table("servo_id", cal, "id"), table("homing_offset", cal, "homing_offset"),
            table("range_min", cal, "range_min"), table("range_max", cal, "range_max"),
            table("drive_mode", cal, "drive_mode"), devices("device", DEVICES), devices("sim_device", SIM_DEVICES)]
    return head + "\n" + "\n\n".join(body) + "\n"


def main():
    args = sys.argv[1:]
    text = generate(args[0])
    if len(args) == 3 and args[1] == "--check":
        if Path(args[2]).read_text() != text:
            print(f"{args[2]} is stale: regenerate with scripts/gen_robot.py")
            return 1
        print(f"{args[2]}: up to date")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
